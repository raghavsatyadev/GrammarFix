  Shapes(
    extraSmall = RoundedCornerShape(4.dp),
    small = RoundedCornerShape(8.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(28.dp),
  )

/**
 * The app's theme. Dark unless asked otherwise: the app ships dark only, and [darkTheme] exists so
 * screenshot tests can hold the light scheme to the same standard.
 */
@Composable
fun AppTheme(darkTheme: Boolean = true, content: @Composable () -> Unit) {
  MaterialExpressiveTheme(
    colorScheme = if (darkTheme) darkScheme else lightScheme,
    typography = getAppTypoGraphy(),
    shapes = appShapes,
    motionScheme = MotionScheme.expressive(),
    content = content,
  )
}
