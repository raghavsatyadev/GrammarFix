"""Generate the GrammarFix logo for every platform from one geometry.

The mark is a white speech bubble (the floating suggestion bubble) holding a checkmark, with a
small spark for the on-device model. Run from the repo root: python tools/make_logo.py
Writes the Android adaptive-icon layers, the legacy mipmaps, the iOS 1024 icon and docs/media.
"""

from pathlib import Path

from PIL import Image, ImageColor, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "androidCMP/src/main/res"

BLUE = "#415F91"  # theme primaryLight
BLUE_DARK = "#284777"  # theme onPrimaryContainerLight
WHITE = "#FFFFFF"
SPARK = "#FFC94D"

# Geometry in the 108x108 adaptive-icon viewport (safe zone is the centered 66-unit circle).
BUBBLE = (24, 34, 76, 72, 12)  # left, top, right, bottom, corner radius
TAIL = [(32, 70), (46, 70), (29, 82)]
CHECK = [(37, 53), (46, 62), (63, 44)]
CHECK_WIDTH = 7
SPARK_C, SPARK_R = (74, 33), 9
SPARK_PINCH = 0.22  # how far each side bows in; 0 is a sharp spike


def bubble_path() -> str:
    l, t, r, b, c = BUBBLE
    rect = (
        f"M{l + c},{t}H{r - c}A{c},{c} 0,0 1,{r},{t + c}V{b - c}A{c},{c} 0,0 1,{r - c},{b}"
        f"H{l + c}A{c},{c} 0,0 1,{l},{b - c}V{t + c}A{c},{c} 0,0 1,{l + c},{t}Z"
    )
    tail = "M{},{}L{},{}L{},{}Z".format(*TAIL[0], *TAIL[1], *TAIL[2])
    return rect + tail


def check_path() -> str:
    return "M{},{}L{},{}L{},{}".format(*CHECK[0], *CHECK[1], *CHECK[2])


def spark_points():
    """The four tips and the control point between each pair, clockwise from the top."""
    x, y, r = *SPARK_C, SPARK_R
    p = r * SPARK_PINCH
    tips = [(x, y - r), (x + r, y), (x, y + r), (x - r, y)]
    ctrls = [(x + p, y - p), (x + p, y + p), (x - p, y + p), (x - p, y - p)]
    return tips, ctrls


def spark_path() -> str:
    tips, ctrls = spark_points()
    path = "M{:g},{:g}".format(*tips[0])
    for i, (cx, cy) in enumerate(ctrls):
        path += "Q{:g},{:g} {:g},{:g}".format(cx, cy, *tips[(i + 1) % 4])
    return path + "Z"


def foreground_xml(mono: bool = False) -> str:
    # Themed (monochrome) icons get one colour, so the bubble becomes an outline there.
    if mono:
        bubble = f"""
    <path
        android:pathData="{bubble_path()}"
        android:strokeColor="#000000"
        android:strokeWidth="4"
        android:strokeLineJoin="round" />"""
    else:
        bubble = f"""
    <path
        android:fillColor="{WHITE}"
        android:pathData="{bubble_path()}" />"""
    check_color = "#000000" if mono else BLUE
    spark = "#000000" if mono else SPARK
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_logo.py; edit the script, not this file. -->
<vector
    xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">{bubble}
    <path
        android:pathData="{check_path()}"
        android:strokeColor="{check_color}"
        android:strokeWidth="{CHECK_WIDTH}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />
    <path
        android:fillColor="{spark}"
        android:pathData="{spark_path()}" />
</vector>
"""


def logo_svg() -> str:
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="512" height="512">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{BLUE}"/>
      <stop offset="1" stop-color="{BLUE_DARK}"/>
    </linearGradient>
  </defs>
  <rect x="18" y="18" width="72" height="72" rx="16" fill="url(#bg)"/>
  <path fill="{WHITE}" d="{bubble_path()}"/>
  <path fill="none" stroke="{BLUE}" stroke-width="{CHECK_WIDTH}" stroke-linecap="round"
        stroke-linejoin="round" d="{check_path()}"/>
  <path fill="{SPARK}" d="{spark_path()}"/>
</svg>
"""


def quad(p0, p1, p2, steps=24):
    return [
        (
            (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
            (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1],
        )
        for t in (i / steps for i in range(steps + 1))
    ]


def render(px: int, shape: str) -> Image.Image:
    """Render the 18..90 crop of the viewport at px, background 'square', 'round' or 'full'."""
    ss = 4
    size = px * ss
    k = size / 72

    def m(x, y):
        return ((x - 18) * k, (y - 18) * k)

    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    ramp = Image.new("RGB", (1, 2))
    ramp.putpixel((0, 0), ImageColor.getrgb(BLUE))
    ramp.putpixel((0, 1), ImageColor.getrgb(BLUE_DARK))
    bg = ramp.resize((size, size), Image.BILINEAR)
    mask = Image.new("L", (size, size), 0)
    md = ImageDraw.Draw(mask)
    if shape == "round":
        md.ellipse((0, 0, size - 1, size - 1), fill=255)
    elif shape == "square":
        md.rounded_rectangle((0, 0, size - 1, size - 1), radius=int(16 * k), fill=255)
    else:
        md.rectangle((0, 0, size, size), fill=255)
    img.paste(bg, (0, 0), mask)

    d = ImageDraw.Draw(img)
    l, t, r, b, c = BUBBLE
    d.rounded_rectangle((*m(l, t), *m(r, b)), radius=c * k, fill=WHITE)
    d.polygon([m(*p) for p in TAIL], fill=WHITE)
    w = CHECK_WIDTH * k
    pts = [m(*p) for p in CHECK]
    d.line(pts, fill=BLUE, width=int(w), joint="curve")
    for x, y in (pts[0], pts[-1]):
        d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=BLUE)
    tips, ctrls = spark_points()
    star = []
    for i, ctrl in enumerate(ctrls):
        star += quad(tips[i], ctrl, tips[(i + 1) % 4])
    d.polygon([m(*p) for p in star], fill=SPARK)
    return img.resize((px, px), Image.LANCZOS)


def main() -> None:
    (RES / "drawable/ic_launcher_foreground.xml").write_text(foreground_xml(), encoding="utf-8")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        foreground_xml(mono=True), encoding="utf-8"
    )
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{BLUE}</color>\n</resources>\n',
        encoding="utf-8",
    )
    for dpi, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        render(px, "square").save(RES / f"mipmap-{dpi}/ic_launcher.png")
        render(px, "round").save(RES / f"mipmap-{dpi}/ic_launcher_round.png")
    ios = ROOT / "iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/app-icon-1024.png"
    render(1024, "full").convert("RGB").save(ios)  # iOS rejects alpha in the app icon
    media = ROOT / "docs/media"
    (media / "logo.svg").write_text(logo_svg(), encoding="utf-8")
    render(512, "square").save(media / "logo-512.png")
    render(512, "full").convert("RGB").save(media / "play-store-icon-512.png")


if __name__ == "__main__":
    main()
