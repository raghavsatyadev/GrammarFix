"""Generate the GrammarFix logo for every platform from one geometry.

The mark is two lines of text over a red error squiggle that a yellow check has fixed, on a teal
tile. Run from the repo root: python tools/make_logo.py
Writes the Android adaptive-icon layers, the legacy mipmaps, the iOS 1024 icon and docs/media.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "androidCMP/src/main/res"

TEAL = "#0F766E"
WHITE = "#FFFFFF"
SQUIGGLE = "#FCA5A5"
CHECK = "#FDE047"

# Geometry is drawn on a 100-unit tile, then mapped into the 18..90 crop of the 108-unit
# adaptive-icon viewport (all marks stay inside the 66-unit safe circle).
LINES = [(22, 28, 78, 37), (22, 45, 62, 54)]  # left, top, right, bottom; fully rounded
SQUIGGLE_PTS = [(22, 70), (25.5, 65), (29, 70), (32.5, 75), (36, 70), (39.5, 65), (43, 70)]
SQUIGGLE_W = 5  # points chain quadratic segments: on, control, on, control, ...
CHECK_PTS = [(53, 67), (61, 75), (78, 56)]
CHECK_W = 9
TILE_RADIUS = 24


def v(x: float, y: float) -> tuple[float, float]:
    """Tile units to adaptive-viewport units."""
    return (round(18 + x * 0.72, 2), round(18 + y * 0.72, 2))


def fmt(p) -> str:
    return "{:g},{:g}".format(*p)


def line_path(box, to=v) -> str:
    l, t, r, b = box
    (l, t), (r, b) = to(l, t), to(r, b)
    c = (b - t) / 2
    return (
        f"M{l + c:g},{t:g}H{r - c:g}A{c:g},{c:g} 0,0 1,{r - c:g},{b:g}"
        f"H{l + c:g}A{c:g},{c:g} 0,0 1,{l + c:g},{t:g}Z"
    )


def squiggle_path(to=v) -> str:
    p = [to(*q) for q in SQUIGGLE_PTS]
    return f"M{fmt(p[0])}" + "".join(
        f"Q{fmt(p[i])} {fmt(p[i + 1])}" for i in range(1, len(p), 2)
    )


def check_path(to=v) -> str:
    p = [to(*q) for q in CHECK_PTS]
    return f"M{fmt(p[0])}L{fmt(p[1])}L{fmt(p[2])}"


def stroke_xml(path: str, color: str, width: float) -> str:
    return f"""
    <path
        android:pathData="{path}"
        android:strokeColor="{color}"
        android:strokeWidth="{width:g}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />"""


def foreground_xml(mono: bool = False) -> str:
    white = "#000000" if mono else WHITE
    lines = "".join(
        f"""
    <path
        android:fillColor="{white}"
        android:pathData="{line_path(box)}" />"""
        for box in LINES
    )
    squiggle = stroke_xml(squiggle_path(), "#000000" if mono else SQUIGGLE, SQUIGGLE_W * 0.72)
    check = stroke_xml(check_path(), "#000000" if mono else CHECK, CHECK_W * 0.72)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_logo.py; edit the script, not this file. -->
<vector
    xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">{lines}{squiggle}{check}
</vector>
"""


def logo_svg() -> str:
    def same(x, y):
        return (x, y)

    lines = "".join(f'\n  <path fill="{WHITE}" d="{line_path(b, same)}"/>' for b in LINES)
    stroke = 'fill="none" stroke-linecap="round" stroke-linejoin="round"'
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="512" height="512">
  <rect width="100" height="100" rx="{TILE_RADIUS}" fill="{TEAL}"/>{lines}
  <path {stroke} stroke="{SQUIGGLE}" stroke-width="{SQUIGGLE_W}" d="{squiggle_path(same)}"/>
  <path {stroke} stroke="{CHECK}" stroke-width="{CHECK_W}" d="{check_path(same)}"/>
</svg>
"""


def quad(p0, p1, p2, steps=32):
    return [
        (
            (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
            (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1],
        )
        for t in (i / steps for i in range(steps + 1))
    ]


def render(px: int, shape: str) -> Image.Image:
    """Render the tile at px with background 'square', 'round' or 'full'."""
    ss = 4
    size = px * ss
    k = size / 100

    def m(x, y):
        return (x * k, y * k)

    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if shape == "round":
        d.ellipse((0, 0, size - 1, size - 1), fill=TEAL)
    elif shape == "square":
        d.rounded_rectangle((0, 0, size - 1, size - 1), radius=int(TILE_RADIUS * k), fill=TEAL)
    else:
        d.rectangle((0, 0, size, size), fill=TEAL)

    for l, t, r, b in LINES:
        d.rounded_rectangle((*m(l, t), *m(r, b)), radius=(b - t) / 2 * k, fill=WHITE)

    def stroke(points, color, width):
        w = width * k
        pts = [m(*p) for p in points]
        d.line(pts, fill=color, width=int(w), joint="curve")
        for x, y in pts:  # round caps and smooth joins
            d.ellipse((x - w / 2, y - w / 2, x + w / 2, y + w / 2), fill=color)

    s = SQUIGGLE_PTS
    wave = [s[0]]
    for i in range(1, len(s), 2):
        wave += quad(s[i - 1], s[i], s[i + 1])[1:]
    stroke(wave, SQUIGGLE, SQUIGGLE_W)
    stroke(CHECK_PTS, CHECK, CHECK_W)
    return img.resize((px, px), Image.LANCZOS)


def main() -> None:
    (RES / "drawable/ic_launcher_foreground.xml").write_text(foreground_xml(), encoding="utf-8")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        foreground_xml(mono=True), encoding="utf-8"
    )
    (RES / "values/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{TEAL}</color>\n</resources>\n',
        encoding="utf-8",
    )
    for dpi, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        render(px, "square").save(RES / f"mipmap-{dpi}/ic_launcher.png")
        render(px, "round").save(RES / f"mipmap-{dpi}/ic_launcher_round.png")
    ios = ROOT / "iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/app-icon-1024.png"
    render(1024, "full").convert("RGB").save(ios)  # iOS rejects alpha in the app icon
    media = ROOT / "docs/media"
    (media / "logo.svg").write_text(logo_svg(), encoding="utf-8")
    render(512, "square").save(media / "logo-512.png")
    render(512, "full").convert("RGB").save(media / "play-store-icon-512.png")


if __name__ == "__main__":
    main()
